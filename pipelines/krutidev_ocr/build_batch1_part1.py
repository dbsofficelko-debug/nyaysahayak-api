res_cards, res_chaps = [], []
for n,(num,topic,summ,prov,tags) in enumerate(res_secs):
    label = num if str(num).startswith("अनुसूची") else f"धारा {num}"
    fname = ("schedule_"+num.split("-")[-1]) if str(num).startswith("अनुसूची") else f"sec_{num}"
    res_cards.append(card(f"res_{fname}", RES, RES_DEPT, label,
                          f"{label} — {topic}", summ, prov, tags, label,
                          ctype=("note" if str(num).startswith("अनुसूची") else "rule")))
    body = f"# {label} — {topic}\n\n" + "\n\n".join(prov)
    res_chaps.append(chap(n, num, topic, fname, body, RES))

